#!/usr/bin/env bash
# Build the reference implementation (madmom) in place and record the test
# baseline. This baseline is the honest starting point of the port: whatever
# fails here (missing opencv/pyfftw/pyaudio, NumPy differences) is recorded, not
# "fixed", so that later we can tell our own regressions from pre-existing ones.
#
# Two environment quirks are handled, both without touching the submodule:
#
#   * madmom's setup.py declares `setup_requires=['pytest-runner']`, which makes
#     setuptools try to `pip install` that egg; there is no pip in a nix python
#     environment, so the build dies before compiling anything (observed).
#     tools/build_madmom_ext.py neutralises the egg fetch and runs setup.py
#     unchanged: the requirement only served the removed `setup.py test`.
#   * the build products (*.so, generated *.c) live inside the submodule and are
#     ignored by madmom's own .gitignore; the submodule therefore stays clean.
#
# Result: third_party/madmom/*.so and tools/reference-baseline.txt.
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
madmom="${root}/third_party/madmom"
out="${root}/tools/reference-baseline.txt"

# One package set for build, import and tests, so the three steps cannot drift:
# madmom's __init__ imports mido, and it reads its own version via
# importlib.metadata, which is why build_madmom_ext.py also runs egg_info.
PY_PACKAGES='ps.numpy ps.scipy ps.cython ps.setuptools ps.mido ps.pytest'
BUILD_PACKAGES="python3.withPackages(ps: [${PY_PACKAGES}])"
TEST_PACKAGES="${BUILD_PACKAGES}"

[ -f "${madmom}/setup.py" ] || {
  echo "error: ${madmom} is empty; run: git submodule update --init --recursive" >&2; exit 1; }
[ -d "${madmom}/madmom/models" ] || {
  echo "error: ${madmom}/madmom/models is empty (nested submodule);" >&2
  echo "       run: git submodule update --init --recursive" >&2; exit 1; }

echo "==> building madmom's Cython/C extensions in place"
nix-shell -p "${BUILD_PACKAGES}" --run "python3 '${root}/tools/build_madmom_ext.py' '${madmom}'"

echo "==> running the reference test suite (baseline)"
{
  echo "# madmom reference baseline"
  echo "# generated by tools/build_reference.sh"
  echo "# python: $(nix-shell -p "${TEST_PACKAGES}" --run 'python3 -c "import sys, numpy, scipy; print(sys.version.split()[0], \"numpy\", numpy.__version__, \"scipy\", scipy.__version__)"' | tail -1)"
  echo "# note: failures caused by missing optional dependencies (opencv, pyfftw, pyaudio)"
  echo "#       are recorded as-is; they are the starting point of the port, not regressions."
  echo
} > "${out}"
set +e
nix-shell -p "${TEST_PACKAGES}" --run \
  "cd '${madmom}' && python3 -m pytest tests -q -p no:cacheprovider --no-header" 2>&1 | tee -a "${out}"
status=${PIPESTATUS[0]}
set -e
echo "==> pytest exit status ${status}; baseline written to ${out}"
echo "    (non-zero is expected while optional dependencies are missing)"
