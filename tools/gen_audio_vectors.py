#!/usr/bin/env python3
"""Generate reference vectors for the Rust audio port from madmom itself.

Writes `crates/madmom-audio/tests/signal_vectors.rs`: every number in it is the
output of the reference implementation (madmom 0.17.dev0 + numpy/scipy of the dev
shell), produced by calling madmom's own `audio.signal` functions. That makes the
generated tests answer "does our port reproduce madmom", not "does it match what we
expected" — which is the only useful question for a port.

Run from the repository root, with madmom built in place:

    nix-shell -p 'python3.withPackages(ps: [ps.numpy ps.scipy ps.mido])' --run \\
      'python3 tools/gen_audio_vectors.py third_party/madmom'
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

OUT = Path("crates/madmom-audio/tests/signal_vectors.rs")

SIG = np.array([1, 2, 3, 4, 5, 6, 7, 8], dtype=np.float32)
SIG2D = np.array([[1, 2], [3, 4], [5, 6], [7, 8]], dtype=np.float32)
INT16 = np.array([-16384, -8192, 0, 8192, 16384], dtype=np.int16)
STEREO = np.array([[100, 200], [300, 401], [-500, -501]], dtype=np.int16)
TRIM_IN = np.array([0, 0, 1, 2, 3, 0, 0], dtype=np.float32)
FRAME_SIG = np.array([0, 1, 2, 3, 4], dtype=np.float32)


def hanning_ref(size):
    """np.hanning, spelled out so the generator does not depend on the reference."""
    return np.hanning(size)


def fmt_f64(values):
    """Format a float64 array as a Rust slice expression."""
    return "&[" + ", ".join(f"{float(v)!r}" for v in np.asarray(values).ravel()) + "]"


def arr(values, indent="        "):
    """Format an array as a Rust slice expression."""
    flat = np.asarray(values).ravel()
    parts = [f"{float(v)!r}" for v in flat]
    body = ", ".join(parts)
    return f"&[{body}]"


def matrix(values, indent="        "):
    rows = np.asarray(values)
    if rows.ndim == 1:
        rows = rows[:, np.newaxis]
    # a slice of row slices, i.e. exactly what arr2(&[&[..]]) expects
    return "&[" + ", ".join(arr(row) for row in rows) + "]"


def main(argv):
    if len(argv) != 2:
        raise SystemExit(__doc__)
    sys.path.insert(0, str(Path(argv[1]).resolve()))

    from madmom.audio.signal import (FramedSignal, Signal, adjust_gain, attenuate, energy,
                                     normalize, remix, rescale, root_mean_square, signal_frame,
                                     smooth, sound_pressure_level, trim)

    out = []
    w = out.append

    w('//! Reference vectors for `madmom_audio::signal`.')
    w('//!')
    w('//! Generated by `tools/gen_audio_vectors.py` — do not edit by hand. Every number')
    w('//! below is what madmom (0.17.dev0) computed for the same input, so these tests')
    w('//! verify the port against the reference rather than against our expectations.')
    w('')
    w('#![allow(clippy::excessive_precision)]')
    w('')
    w('use madmom_audio::signal::{')
    w('    adjust_gain, attenuate, energy, normalize, remix, rescale, root_mean_square,')
    w('    signal_frame, smooth, sound_pressure_level, trim, DType, EndOfSignal, FramedSignal,')
    w('    Origin, Signal, Smoothing,');
    w('};')
    w('use ndarray::{Array1, Array2, ArrayD};')
    w('')
    w('fn arr1(values: &[f32]) -> Array1<f32> {')
    w('    Array1::from(values.to_vec())')
    w('}')
    w('')
    w('fn arr2(rows: &[&[f32]]) -> Array2<f32> {')
    w('    let height = rows.len();')
    w('    let width = rows.first().map(|row| row.len()).unwrap_or(0);')
    w('    let mut out = Array2::zeros((height, width));')
    w('    for (r, row) in rows.iter().enumerate() {')
    w('        for (c, value) in row.iter().enumerate() {')
    w('            out[[r, c]] = *value;')
    w('        }')
    w('    }')
    w('    out')
    w('}')
    w('')
    w('/// Compare two flat buffers with an absolute tolerance.')
    w('fn close(got: &[f32], expected: &[f32], atol: f32, what: &str) {')
    w('    assert_eq!(got.len(), expected.len(), "{what}: length differs");')
    w('    for (index, (got, expected)) in got.iter().zip(expected).enumerate() {')
    w('        assert!(')
    w('            (got - expected).abs() <= atol,')
    w('            "{what}: index {index}: got {got}, reference {expected}"')
    w('        );')
    w('    }')
    w('}')
    w('')
    w('fn flat(array: &ArrayD<f32>) -> Vec<f32> {')
    w('    array.iter().copied().collect()')
    w('}')
    w('')

    # ---- smooth -----------------------------------------------------------------
    w('#[test]')
    w('fn smooth_matches_the_reference() {')
    w(f'    let signal = arr1({arr(SIG)});')
    for label, result, kernel in (
        ("kernel size 3 (Hamming)", smooth(SIG, 3), 'Smoothing::Size(3)'),
        ("kernel size 4 (Hamming, even)", smooth(SIG, 4), 'Smoothing::Size(4)'),
        ("explicit kernel", smooth(SIG, np.array([0.25, 0.5, 0.25])),
         'Smoothing::Kernel(arr1(&[0.25, 0.5, 0.25]))'),
    ):
        w(f'    // {label}')
        w(f'    let got = smooth(signal.view().into_dyn(), &{kernel}).unwrap();')
        w(f'    close(&flat(&got), {arr(result)}, 1e-6, "smooth {label}");')
    w('')
    w('    // 2-D signal: scipy.signal.convolve2d(signal, kernel[:, None], "same")')
    w(f'    let matrix = arr2({matrix(SIG2D)});')
    w(f'    let got = smooth(matrix.view().into_dyn(), &Smoothing::Size(3)).unwrap();')
    w(f'    close(&flat(&got), {arr(smooth(SIG2D, 3))}, 1e-6, "smooth 2-D");')
    w('}')
    w('')

    # ---- gain / attenuate / normalize ------------------------------------------
    w('#[test]')
    w('fn gain_normalize_and_rescale_match_the_reference() {')
    w(f'    let float_signal = arr1({arr(SIG)});')
    w(f'    let got = adjust_gain(float_signal.view().into_dyn(), DType::Float32, 6.0).unwrap();')
    w(f'    close(&flat(&got), {arr(adjust_gain(SIG, 6.0))}, 1e-5, "adjust_gain +6 dB");')
    w(f'    let got = attenuate(float_signal.view().into_dyn(), DType::Float32, 6.0).unwrap();')
    w(f'    close(&flat(&got), {arr(attenuate(SIG, 6.0))}, 1e-5, "attenuate 6 dB");')
    w('')
    w(f'    let int_signal = arr1({arr(INT16)});')
    w(f'    let got = attenuate(int_signal.view().into_dyn(), DType::Int16, 6.0).unwrap();')
    w(f'    close(&flat(&got), {arr(attenuate(INT16, 6.0))}, 1e-6, "attenuate 6 dB (int16)");')
    w(f'    let got = normalize(int_signal.view().into_dyn(), DType::Int16).unwrap();')
    w(f'    close(&flat(&got), {arr(normalize(INT16))}, 1e-6, "normalize (int16)");')
    w(f'    let got = normalize(float_signal.view().into_dyn(), DType::Float32).unwrap();')
    w(f'    close(&flat(&got), {arr(normalize(SIG))}, 1e-6, "normalize (float32)");')
    w(f'    let got = rescale(int_signal.view().into_dyn(), DType::Int16).unwrap();')
    w(f'    close(&flat(&got), {arr(rescale(INT16))}, 1e-9, "rescale (int16)");')
    w('}')
    w('')

    # ---- remix -----------------------------------------------------------------
    w('#[test]')
    w('fn remix_matches_the_reference() {')
    w(f'    let stereo = arr2({matrix(STEREO)});')
    w(f'    let got = remix(stereo.view().into_dyn(), DType::Int16, Some(1), None).unwrap();')
    w(f'    close(&flat(&got), {arr(remix(STEREO, 1))}, 1e-6, "remix stereo -> mono (mean, truncated)");')
    w(f'    let got = remix(stereo.view().into_dyn(), DType::Int16, Some(1), Some(1)).unwrap();')
    w(f'    close(&flat(&got), {arr(remix(STEREO, 1, 1))}, 1e-6, "remix stereo -> channel 1");')
    w(f'    let mono = arr1({arr(INT16)});')
    w(f'    let got = remix(mono.view().into_dyn(), DType::Int16, Some(2), None).unwrap();')
    w(f'    assert_eq!(got.shape(), &[{len(INT16)}, 2]);')
    w('}')
    w('')

    # ---- trim ------------------------------------------------------------------
    w('#[test]')
    w('fn trim_matches_the_reference() {')
    w(f'    let signal = arr1({arr(TRIM_IN)});')
    for where in ("fb", "f", "b"):
        w(f'    let got = trim(signal.view().into_dyn(), "{where}");')
        w(f'    close(&flat(&got), {arr(trim(TRIM_IN, where))}, 1e-6, "trim {where}");')
    w('}')
    w('')

    # ---- energy / rms / spl ----------------------------------------------------
    w('#[test]')
    w('fn energy_rms_and_sound_pressure_level_match_the_reference() {')
    w(f'    let float_signal = arr1({arr(SIG)});')
    w(f'    assert!((energy(float_signal.view().into_dyn()) - {float(energy(SIG))!r}).abs() < 1e-6);')
    w(f'    assert!((root_mean_square(float_signal.view().into_dyn()) - {float(root_mean_square(SIG))!r}).abs() < 1e-9);')
    w(f'    assert!((sound_pressure_level(float_signal.view().into_dyn(), DType::Float32, None) - {float(sound_pressure_level(SIG))!r}).abs() < 1e-9);')
    w(f'    let int_signal = arr1({arr(INT16)});')
    w(f'    assert!((energy(int_signal.view().into_dyn()) - {float(energy(INT16))!r}).abs() < 1e-3);')
    w(f'    assert!((sound_pressure_level(int_signal.view().into_dyn(), DType::Int16, None) - {float(sound_pressure_level(INT16))!r}).abs() < 1e-9);')
    w('}')
    w('')

    # ---- signal_frame ----------------------------------------------------------
    w('#[test]')
    w('fn signal_frame_matches_the_reference_including_padding() {')
    w(f'    let signal = arr1({arr(FRAME_SIG)});')
    w('    // (index, frame_size, hop, numeric origin, reference samples)')
    w('    let cases: &[(i64, usize, f64, i64, &[f32])] = &[')
    for index, frame_size, hop, origin in ((0, 4, 2.0, 0), (2, 4, 2.0, 0), (1, 4, 2.0, 1),
                                           (1, 4, 2.0, -2)):
        frame = signal_frame(FRAME_SIG.astype(float), index, frame_size=frame_size,
                             hop_size=hop, origin=origin)
        label = {0: "centre", 1: "online", -2: "stream"}.get(origin, "origin")
        w(f'        ({index}, {frame_size}, {float(hop)!r}, {origin}, {arr(frame)}),  // {label}')
    w('    ];')
    w('    for (index, frame_size, hop, origin, expected) in cases {')
    w('        let got = signal_frame(signal.view(), *index, *frame_size, *hop, *origin, 0.0);')
    w('        close(&flat(&got.into_dyn()), expected, 1e-6, "signal_frame");')
    w('    }')
    w('}')
    w('')
    w('#[test]')
    w('fn frame_origins_translate_like_the_reference() {')
    w('    let frame_size = 2048;')
    w('    assert_eq!(Origin::Center.value(frame_size), 0);')
    w(f'    assert_eq!(Origin::Online.value(frame_size), {(2048 - 1) // 2});')
    w(f'    assert_eq!(Origin::Stream.value(frame_size), {-((2048) // 2)});')
    w('    assert_eq!(Origin::Numeric(7).value(frame_size), 7);')
    w('}')
    w('')

    # ---- framing ---------------------------------------------------------------
    frames_normal = np.ceil(len(np.arange(10)) / 2.0)
    signal_obj = Signal(np.arange(10, dtype=np.float32), sample_rate=2)
    normal = FramedSignal(signal_obj, frame_size=4, hop_size=2, end='normal')
    extend = FramedSignal(signal_obj, frame_size=4, hop_size=2, end='extend')
    w('#[test]')
    w('fn framed_signal_counts_frames_like_the_reference() {')
    w(f'    let signal = Signal::mono(arr1({arr(np.arange(10, dtype=np.float32))}), DType::Float32, Some(2));')
    w(f'    let normal = FramedSignal::new(signal.clone(), 4, 2.0, Origin::Center, EndOfSignal::Normal);')
    w(f'    assert_eq!(normal.num_frames(), {int(normal.num_frames)});')
    w(f'    assert_eq!(normal.frame_rate(), Some({float(normal.fps)!r}));')
    w(f'    assert!((normal.overlap_factor() - {float(normal.overlap_factor)!r}).abs() < 1e-12);')
    w(f'    let extend = FramedSignal::new(signal, 4, 2.0, Origin::Center, EndOfSignal::Extend);')
    w(f'    assert_eq!(extend.num_frames(), {int(extend.num_frames)});')
    w('}')
    w('')
    w('#[test]')
    w('fn framed_signal_frames_match_the_reference() {')
    w(f'    let signal = Signal::mono(arr1({arr(FRAME_SIG)}), DType::Float32, Some(4));')
    w(f'    let framed = FramedSignal::new(signal, 4, 2.0, Origin::Center, EndOfSignal::Normal);')
    w(f'    assert_eq!(framed.num_frames(), {int(np.ceil(len(FRAME_SIG) / 2.0))});')
    ref = FramedSignal(Signal(FRAME_SIG, sample_rate=4), frame_size=4, hop_size=2)
    w(f'    let expected: Vec<Vec<f32>> = vec![')
    for frame in ref:
        w(f'        vec![{arr(np.asarray(frame, dtype=np.float32))[2:-1]}],')
    w('    ];')
    w('    for (index, expected) in expected.iter().enumerate() {')
    w('        close(&flat(&framed.frame(index)), expected, 1e-6, "frame");')
    w('    }')
    w('}')

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("wrote", OUT, len("\n".join(out)), "chars")

    # ------------------------------------------------------------------ STFT ----
    from madmom.audio.stft import fft_frequencies, stft as reference_stft

    out2 = []
    v = out2.append
    v('//! Reference vectors for `madmom_audio::stft`.')
    v('//!')
    v('//! Generated by `tools/gen_audio_vectors.py` — do not edit by hand. The numbers')
    v('//! are madmom\'s own output for the same input, including the cases the golden')
    v('//! STFT dump does not cover: circular shifting, an FFT longer than the frame,')
    v('//! the Nyquist bin and float frames (no window scaling).')
    v('')
    v('#![allow(clippy::excessive_precision)]')
    v('')
    v('use madmom_audio::stft::{fft_frequencies, hamming, hanning, stft};')
    v('use num_complex::Complex32;')
    v('')
    v('fn complex(values: &[(f32, f32)]) -> Vec<Complex32> {')
    v('    values.iter().map(|(re, im)| Complex32::new(*re, *im)).collect()')
    v('}')
    v('')
    v('fn close_real(got: &[f64], expected: &[f64], atol: f64, what: &str) {')
    v('    assert_eq!(got.len(), expected.len(), "{what}: length differs");')
    v('    for (index, (got, expected)) in got.iter().zip(expected).enumerate() {')
    v('        assert!(')
    v('            (got - expected).abs() <= atol,')
    v('            "{what}: index {index}: got {got}, reference {expected}"')
    v('        );')
    v('    }')
    v('}')
    v('')
    v('fn close_complex(got: &[Complex32], expected: &[Complex32], atol: f32, what: &str) {')
    v('    assert_eq!(got.len(), expected.len(), "{what}: length differs");')
    v('    for (index, (got, expected)) in got.iter().zip(expected).enumerate() {')
    v('        assert!(')
    v('            (*got - *expected).norm() <= atol,')
    v('            "{what}: index {index}: got {got}, reference {expected}"')
    v('        );')
    v('    }')
    v('}')
    v('')

    v('#[test]')
    v('fn fft_frequencies_match_the_reference() {')
    for bins, rate in ((5, 10.0), (4, 44100.0), (1024, 44100.0)):
        values = fft_frequencies(bins, rate)
        v(f'    close_real(&fft_frequencies({bins}, {rate!r}).to_vec(), {fmt_f64(values)}, 1e-9,')
        v(f'        "fft_frequencies({bins}, {rate:g})");')
    v('}')
    v('')

    v('#[test]')
    v('fn windows_match_numpy() {')
    for size in (1, 2, 3, 4, 8, 2048):
        v(f'    close_real(&hanning({size}).to_vec(), {fmt_f64(hanning_ref(size))}, 1e-12, "hanning({size})");')
        v(f'    close_real(&hamming({size}).to_vec(), {fmt_f64(np.hamming(size))}, 1e-12, "hamming({size})");')
    v('}')

    # small STFT cases, all computed by madmom itself
    frames = np.array([[1, 2, 3, 4, 5, 6, 7, 8], [8, 7, 6, 5, 4, 3, 2, 1]], dtype=np.float64)
    int_frames = np.array([[1, 2, 3, 4, 5, 6, 7, 8], [8, 7, 6, 5, 4, 3, 2, 1]], dtype=np.int16)
    cases = []
    for label, window, kwargs in (
        ("rectangular window", "ones", {}),
        ("hann window", "hanning", {}),
        ("no window", None, {}),
        ("hann window, Nyquist bin", "hanning", {"include_nyquist": True}),
        ("hann window, circular shift", "hanning", {"circular_shift": True}),
        ("hann window, fft 16", "hanning", {"fft_size": 16}),
        ("hann window, fft 16, circular shift", "hanning", {"fft_size": 16, "circular_shift": True}),
        ("hann window, fft 4 (truncated frame)", "hanning", {"fft_size": 4}),
    ):
        if window == "ones":
            win = np.ones(8)
        elif window == "hanning":
            win = np.hanning(8)
        else:
            win = None
        cases.append((label, win, kwargs, reference_stft(frames, win, **kwargs)))
    # int16 frames with the scaled window: this is the path the processor takes
    scaled = np.hanning(8) / np.iinfo(np.int16).max
    cases.append(("int16 frames, window scaled by 1/32767", scaled, {},
                  reference_stft(int_frames.astype(np.float64), scaled)))

    v('')
    v('#[test]')
    v('fn stft_matches_the_reference_including_the_edge_cases() {')
    v('    let frames: Vec<Vec<f64>> = vec![')
    for row in frames:
        v(f'        vec![{", ".join(repr(float(v)) for v in row)}],')
    v('    ];')
    v('    let mut matrix = ndarray::Array2::zeros((frames.len(), frames[0].len()));')
    v('    for (r, row) in frames.iter().enumerate() {')
    v('        for (c, value) in row.iter().enumerate() {')
    v('            matrix[[r, c]] = *value;')
    v('        }')
    v('    }')
    for index, (label, win, kwargs, result) in enumerate(cases):
        window_expr = "None" if win is None else 'Some(window.view())'
        if win is not None:
            v(f'    // {label}')
            v(f'    let window = ndarray::Array1::from(vec![{", ".join(repr(float(x)) for x in win)}]);')
        else:
            v(f'    // {label}')
        fft_size = kwargs.get("fft_size")
        size_expr = "None" if not fft_size else f"Some({fft_size})"
        v(f'    let got = stft(matrix.view(), {window_expr}, {size_expr},')
        v(f'        {str(kwargs.get("circular_shift", False)).lower()}, {str(kwargs.get("include_nyquist", False)).lower()}).unwrap();')
        values = ", ".join(f"({float(z.real)!r}, {float(z.imag)!r})" for z in result.ravel())
        v(f'    close_complex(&got.iter().copied().collect::<Vec<_>>(),')
        v(f'        &complex(&[{values}]), 1e-5, "{label}");')
    v('}')
    v('')

    out_stft = Path("crates/madmom-audio/tests/stft_vectors.rs")
    out_stft.parent.mkdir(parents=True, exist_ok=True)
    out_stft.write_text("\n".join(out2) + "\n", encoding="utf-8", newline="\n")
    print("wrote", out_stft, len("\n".join(out2)), "chars")


if __name__ == "__main__":
    sys.exit(main(sys.argv))
